import re

_TAG_RE = re.compile(r"<[^>]+>")


def strip_html(text: str) -> str:
    """
    Убирает HTML-теги (в основном <b>...</b>) из текстов локализации.

    В tg-боте некоторые строки в locales/*.py содержат <b>...</b> и
    отправлялись с parse_mode='HTML'. VK не поддерживает HTML-разметку
    в сообщениях, поэтому теги просто вырезаются, а не переносятся в
    какой-то VK-аналог форматирования (в vkbottle есть tools.bold()/italic(),
    но они требуют отдельного параметра format_data при отправке, что
    плохо сочетается с уже собранными .format()-строками — теги в этом
    боте используются только для лёгкого акцента, поэтому это не критично).
    """
    return _TAG_RE.sub("", text)
